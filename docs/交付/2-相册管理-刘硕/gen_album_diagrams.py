import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / 'tools'))
import figstyle as fs
from figure_layout import Figure, usecases, classes, horizontal, vertical, collaboration, ALBUM, CATEGORY
OUT = HERE / 'images'
usecases(OUT,'相册管理模块用例图',['创建相册','修改相册'],[('普通用户',[0,1])])

f=Figure(OUT,'创建相册_活动图')
f.start()
