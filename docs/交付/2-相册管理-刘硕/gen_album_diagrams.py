f.node('a3','修改名称、类别或公开/私有\n属性并提交',24,336,h=60,style=fs.BOX)
f.decision('d2','名称为空？',432)
f.node('a4','更新相册信息',24,544)
f.node('a5','提示修改成功，返回相册列表',24,616)
f.end('end',152,692)
for a,b in [('start','a1'),('a1','d1'),('d1','a2'),('a2','a3'),('a3','d2'),('d2','a4'),('a4','a5'),('a5','end')]:f.down(a,b,'是' if a=='d1' else '否' if a=='d2' else None)
f.error('d2','提示名称为空','a3',yes='是')
f.save(636,740)

