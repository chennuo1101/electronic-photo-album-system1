f.node('a5','提示成功，返回列表并显示新相册',24,496)
f.end('end',152,572)
for a,b in [('start','a1'),('a1','a2'),('a2','a3'),('a3','d1'),('d1','a4'),('a4','a5'),('a5','end')]:f.down(a,b,'否' if a=='d1' else None)
