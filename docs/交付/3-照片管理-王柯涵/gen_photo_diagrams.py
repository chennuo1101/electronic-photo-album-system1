f.line([(254,374),(354,374)]);f.text('否',280,348,24)
f.end('empty_end',560,362);f.line([(534,374),(560,374)])
f.node('a3','点击某个相册',24,448,style=fs.BOX)
f.decision('d2','相册可查看？',524)
f.node('a4','显示相册内照片缩略图网格',24,636)
f.node('a5','点击某张缩略图',24,708,style=fs.BOX)
f.node('a6','显示照片大图、时间、上传者\n及评论列表',24,780,h=60)
f.end('end',152,876)
for a,b in [('start','a1'),('a1','direct'),('direct','a2'),('a2','d1'),('d1','a3'),('a3','d2'),('d2','a4'),('a4','a5'),('a5','a6'),('a6','end')]:f.down(a,b,'否' if a=='direct' else '是' if a in ['d1','d2'] else None)
# 链接直达绕过列表和点击步骤，但必须经过同一个访问权限判断。
f.line([(254,186),(626,186),(626,512),(164,512),(164,524)])
f.text('是',280,160,24);f.text('相册链接',456,486,100)
f.error('d2','该相册为私有，无权查看','a2',channel=596)
f.save(652,924)

