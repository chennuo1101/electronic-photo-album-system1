HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parents[2]/'tools'))
import figstyle as fs
from figure_layout import Figure,usecases,classes,horizontal,vertical,collaboration,ALBUM,PHOTO
OUT=HERE/'images'
usecases(OUT,'照片管理模块用例图',['上传图片','浏览照片'],[('普通用户',[0,1])])
f=Figure(OUT,'上传图片_活动图');f.start()
f.node('a1','进入目标相册，点击“上传图片”',24,72,style=fs.BOX)
f.node('a2','显示文件选择窗口',24,144)
f.node('a3','选择本地图片文件并提交',24,216,style=fs.BOX)
f.decision('d1','格式、大小\n校验通过？',292)
f.node('a4','保存文件并生成缩略图\n记录上传者与上传时间',24,404,h=60)
f.node('a5','提示上传成功，照片显示在相册中',24,500)
f.end('end',152,576)
for a,b in [('start','a1'),('a1','a2'),('a2','a3'),('a3','d1'),('d1','a4'),('a4','a5'),('a5','end')]:f.down(a,b,'是' if a=='d1' else None)
f.error('d1','仅支持 jpg/png/gif\n且不超过 10MB','a3');f.save(636,624)

f=Figure(OUT,'浏览照片_活动图');f.start()
f.node('a1','进入浏览页面或打开相册链接',24,72,style=fs.BOX)
f.decision('direct','通过链接直达？',148)
f.node('a2','加载公开相册及本人全部相册',24,260)
f.decision('d1','存在可见相册？',336)
